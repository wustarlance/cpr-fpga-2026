#!/usr/bin/env python3
"""Generate the small, project-specific Noto CJK bitmap ROM and string table."""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

PROJECT = Path(__file__).resolve().parents[1]


# 固定百分号字模，避免生成结果随主机字体变化。
# 原有ID 0..130保持不变，新字符追加在末尾。
BASE_CHARACTERS = ' 0123456789:/-一下中习亮仅传位余作保偏停充先入再分前剩力加动卡压合后器复学完定对展已常并度开张待循心快急感慢成或拍持按换播放故救教数断时显暂未松标档次正比毫流测浏演点率环知示秒程练继续缺翻者肺自节苏览触计训识请读跟轮载输连适采释错键间随隔障集页频%'
PERCENT_ROWS = [0x0000, 0x0000, 0x0F00, 0x0910, 0x0920, 0x0F40, 0x0040, 0x0080,
                0x0100, 0x02F0, 0x0290, 0x0490, 0x08F0, 0x0000, 0x0000, 0x0000]


def generate(font_path):
    content = json.loads((PROJECT / 'assets/content.zh-CN.json').read_text(encoding='utf-8'))
    messages = content['ui']
    assert len(messages) < 64 and all(len(s) <= 32 for s in messages)
    chars = list(BASE_CHARACTERS)
    chars += sorted(set(''.join(messages)) - set(chars))
    assert len(chars) < 256 and len(chars) == len(set(chars))
    ids = {c: n for n, c in enumerate(chars)}
    font = ImageFont.truetype(str(font_path), 14)
    glyphs = []
    for c in chars:
        if c == '%':
            glyphs.append(list(PERCENT_ROWS))
            continue
        image = Image.new('L', (16, 16))
        d = ImageDraw.Draw(image)
        # Noto's ascender is taller than its visible CJK box. Use a fixed
        # top origin across all glyphs; do not vertically center each symbol.
        d.text((1 if ord(c) > 127 else 3, -4), c, font=font, fill=255)
        box = font.getbbox(c)
        assert box[1] >= 4 and box[3] <= 20, f'Glyph would be clipped vertically: {c}'
        rows = []
        for y in range(16):
            row = 0
            for x in range(16):
                row = (row << 1) | int(image.getpixel((x, y)) >= 96)
            rows.append(row)
        assert c == ' ' or any(rows), f'Missing glyph: {c}'
        glyphs.append(rows)
    rtl = ['// Generated by tools/generate_chinese_font.py. Noto Sans CJK, SIL OFL 1.1.',
           '// Only the %d project glyphs are retained. Row 0 / column 0 are top / left.' % len(chars),
           'module cpr_font16_rom(input wire [7:0] code, input wire [3:0] row,',
           '                      output wire [15:0] row_bits);',
           '    reg [255:0] bitmap;', '    always @(*) begin', '        case(code)']
    for n, (c, rows) in enumerate(zip(chars, glyphs)):
        rtl.append(f"            8'd{n}: bitmap = 256'h{''.join(f'{r:04x}' for r in rows)}; // {c}".rstrip())
    rtl += ["            default: bitmap = 256'd0;", '        endcase', '    end',
            '    assign row_bits = bitmap[255-row*16 -: 16];', 'endmodule', '']
    (PROJECT / 'rtl/cpr_font16_rom.v').write_text('\n'.join(rtl), encoding='utf-8')
    rtl = ['// Generated local character IDs; these are neither UTF-8 bytes nor GB2312.',
           'module cpr_zh_strings(input wire [5:0] message_id, input wire [5:0] index,',
           '                      output wire [7:0] code);',
           '    reg [255:0] message;', '    always @(*) begin', '        case(message_id)']
    for n, message in enumerate(messages):
        encoded = bytes(ids[c] for c in message.ljust(32))
        rtl.append(f"            6'd{n}: message = 256'h{encoded.hex()}; // {message}")
    rtl += ["            default: message = 256'd0;", '        endcase', '    end',
            "    assign code = index < 32 ? message[255-index*8 -: 8] : 8'd0;", 'endmodule', '']
    (PROJECT / 'rtl/cpr_zh_strings.v').write_text('\n'.join(rtl), encoding='utf-8')
    manifest = {'font_name': 'Noto Sans CJK SC Regular', 'font_sha256': hashlib.sha256(font_path.read_bytes()).hexdigest(),
                'font_source': 'https://github.com/notofonts/noto-cjk/tree/main/Sans',
                'license': 'SIL OFL 1.1; see assets/font/OFL.txt',
                'glyph_size': [16, 16], 'glyph_count': len(chars), 'ids': ids,
                'messages': messages, 'glyph_rows_hex': [[f'{r:04x}' for r in g] for g in glyphs]}
    (PROJECT / 'assets/font').mkdir(parents=True, exist_ok=True)
    (PROJECT / 'assets/font/glyphs.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8')
    fixture = PROJECT.parent / 'tests/sim/fixtures/chinese_glyphs.mem'
    fixture.write_text('\n'.join(''.join(f'{r:04x}' for r in g) for g in glyphs) + '\n', encoding='ascii')
    encoded_messages = [ids[c] for message in messages for c in message.ljust(32)]
    (fixture.parent / 'chinese_messages.mem').write_text(
        ''.join(f'{value:02x}\n' for value in encoded_messages), encoding='ascii')
    # 字形预览图与RTL使用同一份位图。
    sheet = Image.new('RGB', (16*24, ((len(chars)+23)//24)*20), '#101820')
    d = ImageDraw.Draw(sheet)
    for n, rows in enumerate(glyphs):
        for y, row in enumerate(rows):
            for x in range(16):
                if row & (1 << (15-x)):
                    d.point(((n%24)*16+x, (n//24)*20+y), fill='#e5edf2')
    sheet.resize((sheet.width*2, sheet.height*2), Image.Resampling.NEAREST).save(PROJECT / 'assets/font/glyph-sheet.png')
    print(f'Generated {len(chars)} glyphs, {len(chars)*32} bitmap bytes, {len(messages)} strings')


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--font', required=True, type=Path)
    generate(p.parse_args().font)
