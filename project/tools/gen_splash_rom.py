#!/usr/bin/env python3
"""Generate the boot-splash BRAM ROMs from a 640x480 PNG.

Outputs three plain-Verilog ROMs (memory array + synchronous read + initial):
  project/rtl/splash_rom_w1.v  logo 圆弧 + 心电波形
  project/rtl/splash_rom_w2.v  中文标题 + 英文副标题
  project/rtl/splash_rom_w3.v  底部“加载中...”

Window geometry is NOT duplicated here: it is parsed out of splash_boot.v
(the same trick burn_wav.py uses for the WAV track LBAs), so changing the
layout is a one-file change.

Storage: 2 bit/pixel (4 grey levels), 4 pixels per byte, MSB = leftmost.
Why not wider words: EG4S20 only has 9Kb (1024x9) blocks and TD packs wide
arrays badly (measured 89 of 64 blocks for the 64-bit-word version), so a
narrow words + content-shaped windows + explicit 1024-word banks bound usage.

This tool never opens a device.
"""
from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

PROJECT = Path(__file__).resolve().parents[1]
RTL = PROJECT / "rtl"
GREY = (0x00, 0x55, 0xAA, 0xFF)          # 2 bit 级别对应的灰阶
GREY_LUT = tuple(GREY[v] if v < 4 else 0 for v in range(256))
WINDOWS = ("W1", "W2", "W3")


def parse_geometry(boot_v: Path) -> dict[str, int]:
    text = boot_v.read_text(encoding="utf-8")
    keys = tuple(f"{w}_{k}" for w in WINDOWS for k in ("X0", "Y0", "W", "H"))
    pattern = "|".join(keys)
    found = {m.group(1): int(m.group(2)) for m in re.finditer(
        rf"localparam\s+[^=\n]*?\b({pattern})\s*=\s*(?:\d+'d)?(\d+)\s*;", text)}
    missing = set(keys) - found.keys()
    if missing:
        raise SystemExit(f"{boot_v}: 缺少 localparam {sorted(missing)}")
    for w in WINDOWS:
        if found[f"{w}_W"] % 4:
            raise SystemExit(f"{boot_v}: {w}_W={found[f'{w}_W']} 必须是 4 的整数倍（4 像素/字）")
    return found


def to_levels(img: Image.Image) -> Image.Image:
    """RGB → 2 bit 级别图（0..3 存成 0/1/2/3 的 L 图）。白内容黑底，保留抗锯齿。"""
    g = img.convert("L")
    out = Image.new("L", g.size, 0)
    src, dst = g.load(), out.load()
    edges = (42, 127, 212)
    for y in range(g.height):
        for x in range(g.width):
            v = src[x, y]
            dst[x, y] = 0 if v < edges[0] else 1 if v < edges[1] else 2 if v < edges[2] else 3
    return out


def draw_loading(levels: Image.Image, font_path: str, font_index: int,
                 x0: int, y0: int, w: int, h: int, size: int) -> Image.Image:
    """把“加载中...”画在 W3 的正中，然后重新量化（文字自带抗锯齿灰阶）。"""
    rgb = Image.merge("RGB", [levels.point(GREY_LUT)] * 3)
    d = ImageDraw.Draw(rgb)
    font = ImageFont.truetype(font_path, size, index=font_index)
    text = "加载中..."
    l, t, r, b = d.textbbox((0, 0), text, font=font)
    d.text((x0 + w // 2 - (l + r) // 2, y0 + h // 2 - (t + b) // 2),
           text, font=font, fill=(255, 255, 255))
    return to_levels(rgb)


def pack_window(levels: Image.Image, x0: int, y0: int, w: int, h: int) -> list[int]:
    """裁窗口，4 像素/字节，最左像素在最高 2 bit。"""
    px = levels.load()
    words: list[int] = []
    for y in range(y0, y0 + h):
        for wx in range(w // 4):
            word = 0
            for i in range(4):
                word = (word << 2) | (px[x0 + wx * 4 + i, y] & 0x3)
            words.append(word)
    return words


def emit_rom(path: Path, module: str, words: list[int], note: str) -> None:
    """Emit synchronous 1024x9 banks with one-cycle data/bank alignment.

    TD maps a single 6144/5120-word array to eight 8192x1 bit planes.
    Explicit 1024-word banks use 9-bit mode and avoid that capacity padding.
    Keep the bank selector in the same read cycle as the bank data.
    """
    if not words or len(words) > 8192:
        raise ValueError("Splash ROM must contain 1..8192 words")
    depth = -(-len(words) // 1024) * 1024
    words = list(words) + [0] * (depth - len(words))
    aw = max(1, (depth - 1).bit_length())
    banks = depth // 1024
    lines = [
        "`timescale 1ns/1ps",
        "// " + "=" * 74,
        f"// {module}.v -- GENERATED by tools/gen_splash_rom.py, do not edit.",
        f"// {note}",
        f"// {depth} words x 9 bits in {banks} explicit 1024-word banks; one-cycle read.",
        "// " + "=" * 74,
        f"module {module} (",
        "    input wire clk,",
        "    input wire [12:0] addr,",
        "    output reg [8:0] data",
        ");",
        f"localparam integer AW = {aw};",
        f"wire [12:0] word_addr = addr & 13'd{(1 << aw)-1};",
        "reg [2:0] bank_q;",
        "always @(posedge clk) bank_q <= word_addr[12:10];",
    ]
    for bank in range(banks):
        lines += [
            f'reg [8:0] mem_{bank} [0:1023]; /* fehdl force_ram=1, ram_style="bram" */',
            f"reg [8:0] data_{bank};",
            "initial begin",
        ]
        for index, value in enumerate(words[bank*1024:(bank+1)*1024]):
            lines.append(f"    mem_{bank}[{index}] = 9'h{value:03x};")
        lines += [
            "end",
            f"always @(posedge clk) data_{bank} <= mem_{bank}[word_addr[9:0]];",
        ]
    lines += ["always @* begin", "    case(bank_q)"]
    lines += [f"        3'd{bank}: data = data_{bank};" for bank in range(banks)]
    # Unmapped addresses were out-of-range in the old array as well.
    lines += ["        default: data = 9'bxxxxxxxxx;", "    endcase", "end", "endmodule", ""]
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--png", type=Path, required=True, help="640x480 开机画面（黑底白内容）")
    ap.add_argument("--boot-v", type=Path, default=RTL / "splash_boot.v")
    ap.add_argument("--font", default="/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc")
    ap.add_argument("--font-index", type=int, default=2, help="Noto Sans CJK SC = 2")
    ap.add_argument("--loading-text-size", type=int, default=20)
    ap.add_argument("--preview", type=Path, default=None, help="设备实际显示效果写 PNG")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    geom = parse_geometry(args.boot_v)
    src = Image.open(args.png).convert("RGB")
    if src.size != (640, 480):
        raise SystemExit(f"{args.png}: 需要 640x480，实际 {src.size}")

    levels = to_levels(src)
    levels = draw_loading(levels, args.font, args.font_index,
                          geom["W3_X0"], geom["W3_Y0"], geom["W3_W"], geom["W3_H"],
                          args.loading_text_size)

    # 窗口外的像素必须是黑的，否则说明素材超出 splash_boot.v 声明的窗口
    px = levels.load()
    outside = 0
    for y in range(480):
        for x in range(640):
            if px[x, y] == 0:
                continue
            for w in WINDOWS:
                if (geom[f"{w}_X0"] <= x < geom[f"{w}_X0"] + geom[f"{w}_W"] and
                        geom[f"{w}_Y0"] <= y < geom[f"{w}_Y0"] + geom[f"{w}_H"]):
                    break
            else:
                outside += 1
    if outside:
        raise SystemExit(f"窗口外有 {outside} 个非黑像素：内容超出 splash_boot.v 声明的窗口，"
                         f"先放大窗口再生成")

    words = {w: pack_window(levels, geom[f"{w}_X0"], geom[f"{w}_Y0"],
                            geom[f"{w}_W"], geom[f"{w}_H"]) for w in WINDOWS}

    if args.preview:
        Image.merge("RGB", [levels.point(GREY_LUT)] * 3).save(args.preview)

    digest = 0x811C9DC5
    lit = {w: 0 for w in WINDOWS}
    for y in range(480):
        for x in range(640):
            v = GREY[px[x, y]]
            digest = ((digest ^ ((v << 16) | (v << 8) | v)) * 0x01000193) & 0xFFFFFFFF
            if px[x, y]:
                for w in WINDOWS:
                    if (geom[f"{w}_X0"] <= x < geom[f"{w}_X0"] + geom[f"{w}_W"] and
                            geom[f"{w}_Y0"] <= y < geom[f"{w}_Y0"] + geom[f"{w}_H"]):
                        lit[w] += 1
                        break

    note = (f"source {args.png.name} sha256 {hashlib.sha256(args.png.read_bytes()).hexdigest()[:16]}, "
            f"text \"加载中...\" size {args.loading_text_size}")
    total = sum(len(v) for v in words.values())
    for w in WINDOWS:
        print(f"{w}: {len(words[w])} bytes ({geom[f'{w}_W']}x{geom[f'{w}_H']} "
              f"@ ({geom[f'{w}_X0']},{geom[f'{w}_Y0']}))")
    print(f"total : {total} bytes = {total * 8} bit "
          f"(9Kb explicit banks {sum(-(-len(v) // 1024) for v in words.values())})")
    print(f"digest: 0x{digest:08x}  (FNV-1a over 640x480 RGB)")
    print("lit   : " + "  ".join(f"{w} {lit[w]}" for w in WINDOWS))

    if args.dry_run:
        print("dry-run: 未写 ROM")
        return 0

    for i, w in enumerate(WINDOWS, start=1):
        emit_rom(RTL / f"splash_rom_w{i}.v", f"splash_rom_w{i}", words[w], note)
    print("wrote " + ", ".join(f"rtl/splash_rom_w{i}.v" for i in (1, 2, 3)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
