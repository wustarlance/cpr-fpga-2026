//=============================================================================
// blink.v —— HX4S20C 上板首日自检（bring-up）
//
// 目的
// ----
// 板子到手后第一次下载，用它确认整条链路是通的：
//     USB 供电 → JTAG 识别 → 位流下载 → FPGA 运行 → 看得见 + 听得见
//
// 为什么不用参考工程 lab_ex5_i2s 做首测
// ------------------------------------
// 那个工程依赖 TF 卡（读 BMP）和 HDMI 显示器。这两样没到货时，
// 下载成功也看不到任何现象，无法区分「板子坏的」和「没插卡」。
// 本工程只用板载 LED + 蜂鸣器，插一根 USB 线就能判断。
//
// 现象
// ----
//   1. 4 个独立 LED 以 1 Hz 做二进制计数 0→15 循环
//        - 若 LED 为高电平点亮：0000 → 0001 → 0010 → 0011 → … → 1111
//        - 若 LED 为低电平点亮：看到的就是上面每个值的反相
//          （两种接法都会看到「有规律的计数」，且能据此判断极性）
//   2. 每次加 1 时蜂鸣器「嘀」一声（80 ms）
//        ⚠️ 蜂鸣器受乒乓开关 SW5 控制，拨下才接通
//   3. 按下 KEY1 复位，计数回到 0
//
// 引脚（依据 03_技术方案/硬件实证_板卡引脚与资源对照.md）
// ------------------------------------------------------
//   clk    = R7   50 MHz 板载有源晶振
//   rst_n  = A2   KEY1，按下为低电平
//   led[0] = A4   LED1
//   led[1] = A3   LED2
//   led[2] = C10  LED3
//   led[3] = B12  LED4
//   buzzer = H11  蜂鸣器，低电平响
//=============================================================================
`timescale 1ns / 1ps

module blink (
    input  wire       clk,      // R7   50 MHz
    input  wire       rst_n,    // A2   KEY1，按下为低
    output reg  [3:0] led,      // A4 / A3 / C10 / B12
    output wire       buzzer    // H11  低电平响
);

    //-------------------------------------------------------------------------
    // 1 秒节拍：计数到 50_000_000-1
    //   26 位足够（2^26 = 67_108_864 > 50_000_000）
    //-------------------------------------------------------------------------
    localparam [25:0] TICK = 26'd49_999_999;

    reg [25:0] cnt;
    reg        tick;            // 单拍脉冲，每个节拍有效一拍

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            cnt  <= 26'd0;
            tick <= 1'b0;
        end else if (cnt == TICK) begin
            cnt  <= 26'd0;
            tick <= 1'b1;
        end else begin
            cnt  <= cnt + 1'b1;
            tick <= 1'b0;
        end
    end

    //-------------------------------------------------------------------------
    // LED：每次节拍加 1（二进制计数，便于一眼看出「板子活着且有规律」）
    //-------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) led <= 4'd0;
        else if (tick) led <= led + 1'b1;
    end

    //-------------------------------------------------------------------------
    // 蜂鸣器：1 kHz 方波，每次节拍响 80 ms
    //   半周期 = 50 MHz / 1 kHz / 2 = 25_000 拍
    //   80 ms  = 50 MHz × 0.08 = 4_000_000 拍
    //-------------------------------------------------------------------------
    reg [14:0] tone_cnt;        // 0 ~ 24_999
    reg        tone;            // 1 kHz 方波本体
    reg [21:0] beep_cnt;        // 0 ~ 4_000_000 (22 位够放 4e6 < 2^22)

    wire beep_win = (beep_cnt < 22'd4_000_000);

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            tone_cnt <= 15'd0;
            tone     <= 1'b0;
            beep_cnt <= 22'd0;
        end else begin
            // 1 kHz 方波
            if (tone_cnt == 15'd24_999) begin
                tone_cnt <= 15'd0;
                tone     <= ~tone;
            end else begin
                tone_cnt <= tone_cnt + 1'b1;
            end

            // 蜂鸣窗口计时：与 LED 加 1 同步重装
            if (tick)                 beep_cnt <= 22'd0;
            else if (beep_win)        beep_cnt <= beep_cnt + 1'b1;
        end
    end

    // 低电平响 → 取反。beep_win 之外恒为高（不响）
    assign buzzer = ~(tone & beep_win);

endmodule
