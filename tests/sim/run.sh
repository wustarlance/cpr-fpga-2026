#!/usr/bin/env bash
# Cross-platform checker is run.py; retains ./run.sh tb_name [wave].
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
PYTHON_BIN="${PYTHON:-python3}"
if [[ "${2:-}" == "wave" ]]; then
    TB_NAME="$1"
    "$PYTHON_BIN" "$HERE/run.py" "$TB_NAME"
    if command -v gtkwave >/dev/null 2>&1 && [[ -f "$HERE/waves/$TB_NAME.vcd" ]]; then
        gtkwave "$HERE/waves/$TB_NAME.vcd" >/dev/null 2>&1 &
    else
        echo "No waveform generated by $TB_NAME, or gtkwave is unavailable."
    fi
else
    exec "$PYTHON_BIN" "$HERE/run.py" "$@"
fi
